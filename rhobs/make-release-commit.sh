#!/usr/bin/env bash
set -euo pipefail

cd "$(git rev-parse --show-toplevel)"

plan=""
checks=true
while (($#)); do
	case "$1" in
	--plan)
		plan="${2:?--plan requires a JSON release plan}"
		shift 2
		;;
	--no-checks)
		checks=false
		shift
		;;
	-h | --help)
		echo "Usage: $0 --plan PLAN.json [--no-checks]"
		exit 0
		;;
	*)
		echo "Unknown argument: $1" >&2
		exit 1
		;;
	esac
done
[[ -n "$plan" ]] || { echo "Use bash rhobs/release.sh plan to create a release plan first" >&2; exit 1; }

bash rhobs/release.sh transform --plan "$plan"
bash rhobs/generate.sh
bash rhobs/release.sh verify
if "$checks"; then
	bash rhobs/ci.sh lint
	bash rhobs/ci.sh unit
	bash rhobs/release.sh check-import
fi

version="$(head -n1 VERSION)"
git add --all
git commit -s -F- <<EOF
chore(release): v${version}

Generated by rhobs/make-release-commit.sh from the immutable source and
scripts commits recorded in rhobs/release.json.
EOF
bash rhobs/release.sh assert-clean
